#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
数据集格式转换脚本：把任意上传的数据集整理成平台可用的 YOLO 标准结构。

支持两类输入：
  1) 有标注数据集：YOLO 格式 txt（图片与 txt 同级 / 独立 labels 目录均可）、VOC XML
  2) 无标注原始数据集：仅整理图片集合并划分 train/val/test，生成占位 data.yaml，
     之后请在平台上使用「AI 预标注」生成标注

用法：
  python scripts/fix_dataset.py <input.zip 或目录> [-o 输出目录] [--split 0.8,0.15,0.05]

输出结构：
  output/
  ├── images/{train,val,test}/*.jpg
  ├── labels/{train,val,test}/*.txt   (无标注时省略)
  ├── classes.txt
  └── data.yaml
"""
import argparse
import shutil
from pathlib import Path
import random
import sys
import zipfile
from collections import defaultdict

IMG_SUFFIX = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}
# 排除可视化预览图（如 *_result.jpg）
EXCLUDE_KEYWORDS = ("_result", "_predict", "_detect")
YAML_TEMPLATE = """# Auto generated by fix_dataset.py
path: {path}
train: {train}
val: {val}
test: {test}
nc: {nc}
names: {names}
"""


def log(msg: str) -> None:
    print(f"[fix_dataset] {msg}", flush=True)


def extract_or_use(src: Path, work: Path) -> Path:
    """输入是 zip 则解压到 work，否则直接使用原目录"""
    if src.suffix.lower() == ".zip":
        work.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(src, "r") as z:
            z.extractall(work)
        # 若解压后只有一层根目录，取其内容
        entries = [p for p in work.iterdir() if p.name != "__MACOSX" and not p.name.startswith(".")]
        if len(entries) == 1 and entries[0].is_dir():
            return entries[0]
        return work
    return src


def collect_images(root: Path) -> list:
    """递归收集所有图片，排除预览图与隐藏文件"""
    imgs = []
    for suf in IMG_SUFFIX:
        for p in root.rglob(f"*{suf}"):
            if any(k in p.name.lower() for k in EXCLUDE_KEYWORDS):
                continue
            if any(part.startswith(".") for part in p.parts):
                continue
            imgs.append(p)
    return sorted(imgs)


def collect_txt_labels(root: Path) -> dict:
    """递归收集所有 YOLO 格式 txt 标注：返回 {相对顶层目录: [txt路径]}"""
    groups = defaultdict(list)
    for p in root.rglob("*.txt"):
        if any(part.startswith(".") for part in p.parts):
            continue
        # 相对根目录的上层目录（用于识别 train/val/test 分组）
        rel = p.relative_to(root)
        group = rel.parts[0] if len(rel.parts) > 1 else "generic"
        groups[group].append(p)
    return groups


def collect_voc_xmls(root: Path) -> list:
    return [p for p in root.rglob("*.xml") if any(part.islower() or True for part in p.parts)]


def match_pairs(images: list, labels: dict) -> tuple:
    """图片<->txt按stem匹配。返回 (匹配对列表[(img, txt)], 无标注图片列表)"""
    pairs, orphans = [], []
    label_by_stem = {p.stem: p for lst in labels.values() for p in lst}
    for img in images:
        txt = label_by_stem.get(img.stem)
        if txt:
            pairs.append((img, txt))
        else:
            orphans.append(img)
    return pairs, orphans


def parse_yolo_txt(txt: Path) -> list:
    lines = []
    with open(txt, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            parts = line.split()
            if len(parts) >= 5:
                lines.append(parts[:5])
    return lines


def look_up_classes(pairs: list) -> list:
    """从 txt 标注中推断类别数，无法推断时用 catalog"""
    max_cls = -1
    for _, txt in pairs:
        for parts in parse_yolo_txt(txt):
            try:
                max_cls = max(max_cls, int(float(parts[0])))
            except ValueError:
                pass
    if max_cls < 0:
        return []
    return [f"class_{i}" for i in range(max_cls + 1)]


def split_names(all_items: list, ratio: tuple, seed: int = 0) -> tuple:
    rng = random.Random(seed)
    items = list(all_items)
    rng.shuffle(items)
    n = len(items)
    n_train = int(n * ratio[0])
    n_val = int(n * ratio[1])
    return items[:n_train], items[n_train:n_train + n_val], items[n_train + n_val:]


def main():
    parser = argparse.ArgumentParser(description="数据集格式转换脚本")
    parser.add_argument("input", help="输入 zip 文件或目录")
    parser.add_argument("-o", "--out", help="输出目录", default=None)
    parser.add_argument("--split", help="train,val,test 划分比例", default="0.8,0.15,0.05")
    parser.add_argument("--name", help="数据集名称（转出 data.yaml 的 names 用逗号分隔）", default=None)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    src = Path(args.input)
    if not src.exists():
        log(f"输入不存在: {src}")
        sys.exit(1)

    ratio = tuple(float(x) for x in args.split.split(","))
    out = Path(args.out) if args.out else Path(str(src) + "_fixed")
    out.mkdir(parents=True, exist_ok=True)

    # 1. 解压/进入目录
    tmp = src.parent / f".fix_tmp_{src.stem}"
    work = extract_or_use(src, tmp)
    log(f"数据集根目录: {work}")

    # 2. 收集图片与标注
    images = collect_images(work)
    if not images:
        log("未找到任何图片，退出！")
        shutil.rmtree(tmp, ignore_errors=True)
        sys.exit(1)
    log(f"找到图片 {len(images)} 张")

    txt_groups = collect_txt_labels(work)
    xmls = collect_voc_xmls(work)
    has_labels = bool(txt_groups) or bool(xmls)

    # 3. 图片按所属 train/val/test 分组
    predict_tags = None

    def split_of(rel: Path):
        first = rel.parts[-2] if len(rel.parts) > 1 else ""
        if first in ("train", "val", "valid", "test"):
            return "val" if first == "valid" else first
        return None

    # 4. 处理两类情况
    pairs_map = defaultdict(list)      # split -> [(img, txt)]
    no_label_imgs = []                 # 无标注的图片
    if has_labels:
        # 情况 A：有标注
        if "generic" in txt_groups and len(txt_groups) == 1:
            # 标注与图片同目录（无法分组），全部配成一对，后续自动划分
            pairs, orphans = match_pairs(images, txt_groups)
            train, val, test = split_names(pairs, ratio, args.seed)
            pairs_map["train"] = train
            pairs_map["val"] = val
            pairs_map["test"] = test
            no_label_imgs = orphans
            log(f"标注与图片同目录：自动划分 train/val/test，无标注图片 {len(orphans)} 张")
        else:
            # 标注按 train/val/test 分组
            for group, txts in txt_groups.items():
                split = "val" if group == "valid" else group
                if split not in ("train", "val", "test"):
                    split = None
                if split is None:
                    # 无法识别的分组 → 全部归入 train，后续由平台处理
                    split = "train"
                for txt in txts:
                    if txt.suffix.lower() == ".txt":
                        pair_img = txt.with_suffix(txt.suffix)
                        for suf in IMG_SUFFIX:
                            cand = txt.with_suffix(suf)
                            if cand.exists():
                                pair_img = cand
                                break
                        if pair_img.exists() and any(k in pair_img.name.lower() for k in EXCLUDE_KEYWORDS):
                            continue
                        pairs_map[split].append((pair_img, txt))
                log(f"  分组 {group} → {split}: {len(txts)} 个标注")
    else:
        # 情况 B：无标注 → 只整理图片
        split_imgs = defaultdict(list)
        for img in images:
            s = split_of(img)
            split_imgs[s if s else "generic"].append(img)
        if len(split_imgs) > 1 or ("generic" not in split_imgs and len(split_imgs) > 0 and len(split_imgs) < 3):
            # 原结构自带 train/val/test
            for s, imgs in split_imgs.items():
                if s == "generic":
                    no_label_imgs.extend(imgs)
                else:
                    pairs_map[s].extend([(im, None) for im in imgs])
        else:
            # 无划分 → 自动划分
            all_imgs = split_imgs.get("generic", []) + [i for lst in split_imgs.values() for i in lst]
            train, val, test = split_names(all_imgs, ratio, args.seed)
            pairs_map["train"] = [(im, None) for im in train]
            pairs_map["val"] = [(im, None) for im in val]
            pairs_map["test"] = [(im, None) for im in test]
        log(f"无标注数据集：已整理并按 {ratio} 划分（请用平台 AI 预标注生成标注）")

    # 5. 写入标准目录
    total_pairs = 0
    all_stems = set()
    for split, pairs in pairs_map.items():
        img_out = out / "images" / split
        lbl_out = out / "labels" / split
        img_out.mkdir(parents=True, exist_ok=True)
        written = 0
        for img, txt in pairs:
            if img is None:
                continue
            dst = img_out / img.name
            shutil.copy2(img, dst)
            if txt is not None and txt.exists():
                lbl_out.mkdir(parents=True, exist_ok=True)
                shutil.copy2(txt, lbl_out / txt.name)
            all_stems.add(img.stem)
            written += 1
        total_pairs += written
        log(f"  [{split}] 图片 {written} 张" + (" + 标注" if (lbl_out.exists() and any(lbl_out.iterdir())) else "（无标注）"))

    # 孤儿图片（有标注模式下没匹配上的）取前N张提示
    if no_label_imgs:
        log(f"警告：有 {len(no_label_imgs)} 张图片找不到对应标注，已跳过。"
            f"示例: {[p.name for p in no_label_imgs[:3]]}")

    # 6. 生成 classes.txt / data.yaml
    classes = []
    if args.name:
        classes = [c.strip() for c in args.name.split(",") if c.strip()]
    if not classes and has_labels:
        n_cls = look_up_classes([(i, t) for lst in pairs_map.values() for i, t in lst if t is not None])
        classes = n_cls if n_cls else []
    yaml_names = classes if classes else ["class_0"]
    nc = len(yaml_names) if classes else 0

    if classes:
        (out / "classes.txt").write_text("\n".join(classes) + "\n", encoding="utf-8")

    train_has = (out / "images" / "train").exists() and any((out / "images" / "train").iterdir())
    val_has = (out / "images" / "val").exists() and any((out / "images" / "val").iterdir())
    test_has = (out / "images" / "test").exists() and any((out / "images" / "test").iterdir())

    yaml_path = out / "data.yaml"
    yaml_path.write_text(YAML_TEMPLATE.format(
        path=str(out.resolve()),
        train="images/train" if train_has else "images",
        val="images/val" if val_has else "images",
        test="images/test" if test_has else "",
        nc=nc,
        names=yaml_names,
    ), encoding="utf-8")

    log(f"完成！输出目录: {out}")
    log(f"图片总数: {total_pairs}, 类别: {classes or '(无标注, nc=0, 请 AI 预标注后填写)'}")
    if not classes:
        log("提示：无标注数据集上传后，请在平台上使用「AI 预标注」生成 labels，再执行训练。")

    # 清理临时解压目录
    shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()